const assert = require('node:assert/strict');
const G = require('../duet/engine');
const L = require('../duet/learn');
const C = require('../duet/challenge');
let s = G.initial(L.level);
const states = [s];
for (const d of ['R', 'W', 'R', 'R', 'W']) { s = L.step(s, d); assert(s); states.push(s); }
assert.deepEqual(states.map(s => [s.a[0], s.b[0]]), [[1,1],[2,1],[2,2],[3,2],[4,3],[4,4]]);
assert.equal(G.gateOpen(L.level, states[1], 0), false, 'orange gate is closed before blue stands on its switch');
assert.equal(G.gateOpen(L.level, states[2], 0), true, 'waiting sends the previous right to blue, opening orange gate');
assert.equal(G.gateOpen(L.level, states[3], 1), true, 'orange stands on the second switch to open blue gate');
assert.equal(states[4].passed[1], true, 'blue genuinely crosses its gate');
assert.equal(G.dock(L.level, states[4], 0), true, 'orange arrives first and stays');
assert.equal(G.won(L.level, states[4]), false);
assert.equal(G.won(L.level, states[5]), true, 'final wait brings blue home');
assert.equal(L.step(states[0], 'W'), null, 'unexpected inputs cannot desynchronize guided actions');
assert.equal(L.step(states[1], 'R'), null);
assert.equal(L.step(states[5], 'R'), null, 'no more actions after lesson win');
assert.deepEqual(L.step(states[3], 'R'), states[4], 'undo can replay the same guided step');
assert.deepEqual(C.readBests('{}'), {}, 'practice is separate from challenge records');
assert.equal(L.shouldStart('', null, false), true);
assert.equal(L.shouldStart('?room=10', null, false), true, 'fresh shared deep link still teaches first');
for (const seen of ['done', 'skipped']) assert.equal(L.shouldStart('', seen, false), false);
assert.equal(L.shouldStart('', null, true), false, 'do not interrupt players with existing progress');
assert.equal(L.shouldStart('?learn=1', 'done', true), true, 'explicit practice link always works');
assert.equal(L.shouldStart('?learn=0', null, false), false);
for (const q of ['', '?room=wat', '?room=-3', '?room=2.5']) assert.equal(L.roomFrom(q), 0);
assert.equal(L.roomFrom('?room=10'), 9);
assert.equal(L.roomFrom('?room=99'), 10);
console.log('PASS: five real interactions teach delay, wait, both switches and permanent docking; undo, input guards and first-visit routing.');
